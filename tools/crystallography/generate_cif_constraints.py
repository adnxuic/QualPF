"""Reproduce the accepted importer table from its frozen exact catalogue."""
import argparse
from fractions import Fraction
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "tests/regression/references/cif/site-symmetry/constraint-catalogue.json"
OUTPUT = ROOT / "src/core/io/cif/cif_site_constraints.inc"


def render():
    data = json.loads(SOURCE.read_bytes())
    # Keep the original provenance comment as part of the accepted table bytes.
    lines = ["// Generated by tests/phase19/site_symmetry_generate.py. Do not hand edit.",
             "// spglib v2.5.0 naming supplement; BSD-3-Clause, see site_symmetry_spglib_COPYING.",
             "// Each family is checked against the frozen Phase 14 exact operations.",
             "constexpr ConstraintFamily constraint_families[] = {"]
    for key, group in data["settings"].items():
        for family in group["families"]:
            for rows in family["constraints"]:
                packed = []
                for row in rows:
                    coefficients = [Fraction(v) for v in row[:3]]
                    rhs = Fraction(row[3])
                    assert all(v.denominator == 1 for v in coefficients)
                    assert 24 % rhs.denominator == 0
                    packed.append("{" + ",".join(str(int(v)) for v in coefficients) + "," + str(int(rhs * 24)) + "}")
                packed += ["{0,0,0,0}"] * (3 - len(rows))
                lines.append("  {" + f"{key},{family['multiplicity']},'{family['letter']}',{len(rows)}," + "{{" + ",".join(packed) + "}}},")
    return "\n".join(lines + ["};", ""]).encode()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    raw = render()
    if args.check:
        # The original text writer used native source-file EOLs; table tokens
        # and exact rational coefficients must still match without alteration.
        if OUTPUT.read_text(encoding="utf-8") != raw.decode():
            raise SystemExit("Accepted CIF constraint table differs")
    else:
        OUTPUT.write_text(raw.decode(), encoding="utf-8")
    print("CIF constraint table verified" if args.check else "CIF constraint table generated")
