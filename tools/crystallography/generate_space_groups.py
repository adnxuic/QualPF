"""Reproduce the compiled table from the pre-implementation frozen native oracle.

Metadata comes from actual Legacy output; exact operations come from the archived
rational source, independently parsed before any C++ implementation. No live C++
output or runtime table loading participates in generation.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import zipfile

ROOT=Path(__file__).resolve().parents[2]
def render():
    manifest=json.loads((ROOT/'tests/data/symmetry-reference-manifest.json').read_text())
    archive=ROOT/'tests/data'/manifest['archive']
    assert hashlib.sha256(archive.read_bytes()).hexdigest()==manifest['archive_sha256']
    with zipfile.ZipFile(archive) as z:
        exact=z.read('exact-table.json')
        assert hashlib.sha256(exact).hexdigest()==manifest['exact_table_sha256']
        groups=sorted(json.loads(exact),key=lambda g:g['id'])
        table=z.read('source/legacy/fortran/crystallography/symm_table.f90').decode()
    quote=lambda s:json.dumps(s,ensure_ascii=True)
    rows=['// Generated by tools/crystallography/generate_space_groups.py; do not edit.',
          '// Frozen archive SHA256: '+manifest['archive_sha256'],
          'constexpr SymmetryOperation operations[] = {']
    offset=0; records=[]
    for g in groups:
        for op in g['operations']:
            rows.append('    SymmetryTableBuilder::operation({'+','.join(map(str,op['rotation']))+'}, {'+','.join(map(str,op['translation_twelfths']))+'}),')
        setting=','.join(map(str,[g['id'],g['setting_index'],g['standard_id']]))+','+','.join(quote(g[k]) for k in ('choice','to_setting','to_standard'))
        records.append('    {'+str(g['number'])+', {'+setting+'}, '+','.join(quote(g[k]) for k in ('xhm','hall','old1','old2','schoenflies'))+', '+','.join(map(str,[g['primitive_count'],g['centering_count'],g['centrosymmetry'],offset,g['operation_count']]))+'},')
        offset+=g['operation_count']
    rows+=['};','constexpr SpaceGroupRecord records[] = {']+records+['};','constexpr std::string_view origin_one_aliases[] = {']
    for row in re.findall(r'sg_info_type\(\s*\d+,([^\n]+)',table):
        hm1=re.findall("'([^']*)'",row)[1].strip()
        if hm1.endswith(':1'): rows.append('    '+quote(hm1)+',')
    rows+=['};','static_assert(std::size(records) == SpaceGroupRegistry::setting_count);','']
    return '\n'.join(rows)

if __name__=='__main__':
    parser=argparse.ArgumentParser(); parser.add_argument('--check',action='store_true'); args=parser.parse_args()
    path=ROOT/'src/core/crystallography/space_group_data.inc'
    output=render()
    if args.check:
        assert path.read_text()==output, 'Generated symmetry table differs'
        print('Generated symmetry table is reproducible')
    else: path.write_text(output,encoding='utf-8',newline='\n')
